# Define the Wide and Deep model architecture
class WideDeepModel(torch.nn.Module):
    def __init__(self, num_features):
        super(WideDeepModel, self).__init__()
        self.linear = torch.nn.Linear(num_features, 1)
        self.deep = torch.nn.Sequential(
            torch.nn.Linear(num_features, 64),
            torch.nn.ReLU(),
            torch.nn.Linear(64, 32),
            torch.nn.ReLU(),
            torch.nn.Linear(32, 1)
        )

    def forward(self, x):
        wide_out = self.linear(x)
        deep_out = self.deep(x)
        combined_out = wide_out + deep_out  # Combine wide and deep outputs
        return combined_out


def download_file(url, filename):
    if not os.path.exists(filename):
        try:
            torch.hub.download_url_to_file(url, filename)
            print(f"Downloaded {filename} from {url}")
        except Exception as e:
            print(f"Error downloading {filename}: {e}")
            return False
    return True


def load_model_and_scaler():
    # Download model and scaler
    model_filename = "model.pth"
    scaler_filename = "scaler.pkl"

    model_downloaded = download_file(MODEL_URL, model_filename)
    scaler_downloaded = download_file(SCALER_URL, scaler_filename)

    if not model_downloaded or not scaler_downloaded:
        raise FileNotFoundError("Failed to download model or scaler.")

    # Load scaler
    try:
        scaler = joblib.load(scaler_filename)
        print("Scaler loaded successfully.")
    except Exception as e:
        raise Exception(f"Error loading scaler: {e}")

    # Load model
    try:
        model = WideDeepModel(num_features=8)  # Assuming 8 features
        model.load_state_dict(torch.load(model_filename, map_location=DEVICE))
        model.to(DEVICE)
        model.eval()
        print("Model loaded successfully.")
    except Exception as e:
        raise Exception(f"Error loading model: {e}")

    return model, scaler

def preprocess_data(df, scaler):
    numerical_features = ['MedInc', 'HouseAge', 'AveRooms', 'AveBedrms', 'Population', 'AveOccup', 'Latitude', 'Longitude']
    df_numerical = df[numerical_features].copy()

    # Handle missing values with median imputation
    for col in numerical_features:
        median_val = df_numerical[col].median()
        df_numerical[col] = df_numerical[col].fillna(median_val)

    scaled_features = scaler.transform(df_numerical)
    return scaled_features

def predict_labels(model, scaled_features):
    model.eval()
    with torch.no_grad():
        inputs = torch.tensor(scaled_features, dtype=torch.float32).to(DEVICE)
        predictions = model(inputs)
        predictions = predictions.cpu().numpy().flatten()
    return predictions

