class ModelLoader:
    def __init__(self, model_name):
        self.model_name = model_name
        self.model = None
        self.tokenizer = None
        self.device = self._get_device()

    def _get_device(self):
        if torch.cuda.is_available():
            device = torch.device('cuda')
            logging.info("CUDA device detected.")
        elif torch.backends.mps.is_available():
            device = torch.device('mps')
            logging.info("MPS device detected.")
        else:
            device = torch.device('cpu')
            logging.info("No CUDA or MPS, using CPU.")
        return device

    def load_model(self):
        try:
            self.tokenizer = AutoTokenizer.from_pretrained(self.model_name)
            self.model = AutoModelForSequenceClassification.from_pretrained(self.model_name).to(self.device)
            self.model.eval()
            logging.info(f"Model '{self.model_name}' loaded successfully on {self.device}.")
        except Exception as e:
            logging.error(f"Error loading model '{self.model_name}': {e}")
            raise

    def get_model(self):
        if self.model is None:
            self.load_model()
        return self.model, self.tokenizer, self.device

