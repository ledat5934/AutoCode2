class InferencePipeline:
    def __init__(self, model, tokenizer, device, label_encoder):
        self.model = model
        self.tokenizer = tokenizer
        self.device = device
        self.label_encoder = label_encoder

    def predict(self, text):
        try:
            # Tokenize the input text
            inputs = self.tokenizer(text, padding=True, truncation=True, return_tensors='pt').to(self.device)

            # Disable gradient calculation for inference
            with torch.no_grad():
                # Perform inference
                outputs = self.model(**inputs)

            # Get predicted probabilities
            probabilities = torch.nn.functional.softmax(outputs.logits, dim=-1)

            # Get the predicted class
            predicted_class_id = torch.argmax(probabilities, dim=-1).item()

            # Decode the predicted label
            predicted_label = self.label_encoder.inverse_transform([predicted_class_id])[0]

            # Get the confidence score
            confidence_score = probabilities[0, predicted_class_id].item()

            logging.info(f"Input text: {text}\nPredicted label: {predicted_label}\nConfidence score: {confidence_score}")

            return predicted_label, confidence_score

        except Exception as e:
            logging.error(f"Inference error: {e}")
            return None, None

