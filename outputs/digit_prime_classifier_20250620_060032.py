class OutputFormatter:
    def __init__(self, label_encoder):
        self.label_encoder = label_encoder

    def format_classification_output(self, predictions, confidence_scores):
        """Formats classification output with readable labels and confidence scores."""
        try:
            # Convert numerical predictions to readable labels
            labels = self.label_encoder.inverse_transform(predictions)
            
            # Create a list of dictionaries, each containing the file name, prediction, and confidence
            formatted_output = [{'prediction': label, 'confidence': confidence} for label, confidence in zip(labels, confidence_scores)]
            
            logging.info("Classification output formatted successfully.")
            return formatted_output
        except Exception as e:
            logging.error(f"Error formatting classification output: {e}")
            return None

    def validate_output(self, output):
        """Validates the formatted output."""
        if not isinstance(output, list):
            logging.error("Output is not a list.")
            return False
        for item in output:
            if not isinstance(item, dict):
                logging.error("Item in output is not a dictionary.")
                return False
            if 'prediction' not in item or 'confidence' not in item:
                logging.error("Item in output does not contain 'prediction' or 'confidence' keys.")
                return False
        logging.info("Output validation successful.")
        return True
